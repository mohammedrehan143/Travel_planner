import { Response } from 'express';
import { AuthenticatedRequest } from '../middleware/auth.js';
import { AgentOrchestrator } from '../agent/orchestrator.js';
import { AgentRunService } from '../services/agentRun.service.js';
import { TripService } from '../services/trip.service.js';
import { PlanTripRequest } from '../types/trip.types.js';
import { processAgentChat, generateChatReply } from '../agent/llm.client.js';
import { detectCurrencyForDestination, getDefaultBudgetForCurrency } from '../integrations/currency.adapter.js';

export class AgentController {
  /** POST /api/agent/chat — conversational endpoint usable with local or saved trips. */
  static async chat(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const { message, context } = req.body as { message: string; context?: Record<string, unknown> };
      const userId = req.user?.id || '00000000-0000-0000-0000-000000000001';

      if (!message || typeof message !== 'string') {
        res.status(400).json({ error: 'Bad Request', message: 'Message string is required.' });
        return;
      }

      const chatResult = await processAgentChat(message, context || {});

      // If user requested to plan a new trip or outing
      if (chatResult.action === 'plan_new_trip' && chatResult.tripParams?.destination) {
        const dest = chatResult.tripParams.destination.trim();
        const durationDays = Math.max(1, Math.min(30, Number(chatResult.tripParams.durationDays) || 1));
        const origin = chatResult.tripParams.origin || (context?.origin as string) || dest;

        const now = new Date();
        const startDateObj = new Date(now.getTime() + 24 * 60 * 60 * 1000);
        const endDateObj = new Date(startDateObj.getTime() + (durationDays - 1) * 24 * 60 * 60 * 1000);
        const formatDate = (d: Date) => d.toISOString().split('T')[0];

        const detectedDestCurrency = detectCurrencyForDestination(dest);
        const currency = (context?.currency as string) || chatResult.tripParams.currency || detectedDestCurrency || 'USD';
        const isBudget = chatResult.tripParams.travelStyle === 'budget' || /budget|cheap/i.test(message);
        const baseDefault = getDefaultBudgetForCurrency(currency, durationDays);
        const defaultBudget = chatResult.tripParams.budget || (isBudget ? Math.round(baseDefault * 0.65) : baseDefault);

        const planReq: PlanTripRequest = {
          userId,
          destination: dest,
          origin,
          startDate: chatResult.tripParams.startDate || formatDate(startDateObj),
          endDate: chatResult.tripParams.endDate || formatDate(endDateObj),
          travelerCount: chatResult.tripParams.travelerCount || 2,
          travelCompanion: chatResult.tripParams.travelCompanion || 'friends',
          travelStyle: (chatResult.tripParams.travelStyle as any) || 'balanced',
          interests: chatResult.tripParams.interests || ['sightseeing', 'culinary', 'culture'],
          budget: chatResult.tripParams.budget || defaultBudget,
          currency,
          dietaryPreference: chatResult.tripParams.dietaryPreference || 'any'
        };

        const planned = await AgentOrchestrator.planTrip(planReq);

        res.status(200).json({
          status: 'success',
          action: 'plan_new_trip',
          message: chatResult.reply || `I have designed and planned an authentic ${durationDays}-day trip to ${dest} for you!`,
          createdTrip: planned.itinerary,
          runId: planned.runId
        });
        return;
      }

      // Standard conversational response generated by LLM
      res.status(200).json({
        status: 'success',
        action: 'chat',
        message: chatResult.reply || 'I am ready to help you plan or explore any destination!'
      });
    } catch (err: any) {
      console.warn('AgentController.chat caught upstream error:', err?.message || err);
      const isRateLimit = err?.message?.includes('429') || err?.status === 429;
      const friendlyMessage = isRateLimit
        ? 'The AI assistant is experiencing high request volume on the free tier. Please wait a moment and try again.'
        : (err.message || 'The AI assistant is temporarily unavailable. Please try again.');
      res.status(200).json({ status: 'success', action: 'chat', message: friendlyMessage });
    }
  }

  /**
   * POST /api/trips/plan
   * Start a trip planning run (supports async background tracking or synchronous return)
   */
  static async planTrip(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const userId = req.user?.id || '00000000-0000-0000-0000-000000000001';
      const body = req.body as PlanTripRequest & { asyncExecution?: boolean };
      body.userId = userId;

      // Create persistent run record
      const runId = await AgentRunService.createRun(userId, body);

      if (body.asyncExecution) {
        // Run in background without blocking HTTP response
        AgentOrchestrator.planTrip(body, runId).catch(err => {
          console.error(`[AgentRun ${runId}] Async execution error:`, err);
        });

        res.status(202).json({
          status: 'accepted',
          message: 'Trip planning run initiated. Poll /api/agent-runs/:id for status.',
          runId,
          checkStatusUrl: `/api/agent-runs/${runId}`
        });
        return;
      }

      // Synchronous execution
      const result = await AgentOrchestrator.planTrip(body, runId);
      res.status(200).json({
        status: 'completed',
        runId,
        itinerary: result.itinerary,
        validation: result.validation
      });
    } catch (err: any) {
      res.status(500).json({
        error: 'Planning Failed',
        message: err.message || 'Failed to complete trip planning run.'
      });
    }
  }

  /**
   * GET /api/agent-runs/:id
   * Retrieve real-time planning status, current step, logs, and final result
   */
  static async getRunStatus(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const runId = String(req.params.id);
      const run = await AgentRunService.getRun(runId);

      if (!run) {
        res.status(404).json({
          error: 'Not Found',
          message: `Agent run with id ${runId} was not found.`
        });
        return;
      }

      res.status(200).json({
        runId: run.id,
        status: run.status,
        currentStep: run.current_step,
        progressPercent: run.progress_percent,
        logs: run.logs,
        result: run.result,
        errorMessage: run.error_message,
        startedAt: run.started_at,
        completedAt: run.completed_at
      });
    } catch (err: any) {
      res.status(500).json({
        error: 'Query Failed',
        message: err.message || 'Failed to fetch agent run status.'
      });
    }
  }

  /**
   * POST /api/trips/:id/modify
   * Modify an existing trip itinerary with natural language instructions
   */
  static async modifyTrip(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const tripId = String(req.params.id);
      const userId = req.user?.id || '00000000-0000-0000-0000-000000000001';
      const { instructions, targetDay } = req.body;

      const trip = await TripService.getTripById(tripId, userId);
      if (!trip) {
        res.status(404).json({ error: 'Trip Not Found', message: `Trip ${tripId} not found.` });
        return;
      }

      // Format as CompleteItinerary for agent modification
      const mockItinerary: any = {
        tripId: trip.id,
        title: trip.title,
        description: trip.description,
        destination: trip.destination,
        origin: trip.origin,
        startDate: trip.start_date,
        endDate: trip.end_date,
        durationDays: trip.duration_days,
        travelerCount: trip.traveler_count,
        travelStyle: trip.travel_style,
        interests: trip.interests,
        totalBudget: trip.total_budget,
        currency: trip.currency,
        destinationCoordinates: {
          lat: trip.destination_lat || 35.6762,
          lng: trip.destination_lng || 139.6503
        },
        days: trip.days.map((d: any) => ({
          dayNumber: d.day_number,
          date: d.date,
          theme: d.theme,
          summary: d.summary,
          activities: d.activities.map((a: any) => ({
            title: a.title,
            description: a.description,
            category: a.category,
            startTime: a.start_time,
            endTime: a.end_time,
            durationMinutes: a.duration_minutes,
            locationName: a.location_name,
            locationAddress: a.location_address,
            latitude: a.latitude,
            longitude: a.longitude,
            estimatedCost: a.estimated_cost,
            currency: a.currency,
            bookingRequired: a.booking_required,
            bookingStatus: a.booking_status,
            orderIndex: a.order_index
          }))
        })),
        budgetBreakdown: {
          currency: trip.currency,
          totalBudget: trip.total_budget,
          estimatedTotalCost: trip.total_budget * 0.9,
          surplusOrDeficit: trip.total_budget * 0.1,
          isWithinBudget: true,
          categories: {},
          costPerTraveler: trip.total_budget / trip.traveler_count,
          recommendations: []
        }
      };

      const result = await AgentOrchestrator.modifyItinerary(mockItinerary, {
        tripId,
        instructions,
        targetDay
      });

      res.status(200).json({
        status: 'success',
        changeSummary: result.changeSummary,
        itinerary: result.modifiedItinerary,
        validation: result.validation
      });
    } catch (err: any) {
      res.status(500).json({
        error: 'Modification Failed',
        message: err.message || 'Failed to apply trip modifications.'
      });
    }
  }

  /**
   * POST /api/trips/:id/days/:dayNumber/regenerate
   * Regenerate a single day
   */
  static async regenerateDay(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const tripId = String(req.params.id);
      const dayNumber = req.body.dayNumber
        ? parseInt(String(req.body.dayNumber), 10)
        : parseInt(String(req.params.dayNumber || '1'), 10);
      const userId = req.user?.id || '00000000-0000-0000-0000-000000000001';
      const customPacing = req.body.customPacing;
      const specificInterests = req.body.specificInterests || (req.body.focus ? [req.body.focus] : undefined);

      const trip = await TripService.getTripById(tripId, userId);
      if (!trip) {
        res.status(404).json({ error: 'Trip Not Found', message: `Trip ${tripId} not found.` });
        return;
      }

      const mockItinerary: any = {
        tripId: trip.id,
        destination: trip.destination,
        currency: trip.currency,
        totalBudget: trip.total_budget,
        destinationCoordinates: {
          lat: trip.destination_lat || 35.6762,
          lng: trip.destination_lng || 139.6503
        },
        days: trip.days.map((d: any) => ({
          dayNumber: d.day_number,
          date: d.date,
          theme: d.theme,
          summary: d.summary,
          activities: d.activities || []
        })),
        budgetBreakdown: { estimatedTotalCost: 1000 }
      };

      const result = await AgentOrchestrator.regenerateDay(mockItinerary, {
        tripId,
        dayNumber,
        customPacing,
        specificInterests
      });

      res.status(200).json({
        status: 'success',
        dayNumber,
        day: result.regeneratedDay,
        regeneratedDay: result.regeneratedDay,
        validation: result.validation
      });
    } catch (err: any) {
      res.status(500).json({
        error: 'Regeneration Failed',
        message: err.message || 'Failed to regenerate day.'
      });
    }
  }

  /**
   * POST /api/trips/:id/validate
   * Run validation on an itinerary
   */
  static async validateTrip(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const tripId = String(req.params.id);
      const userId = req.user?.id || '00000000-0000-0000-0000-000000000001';

      const trip = await TripService.getTripById(tripId, userId);
      if (!trip) {
        res.status(404).json({ error: 'Trip Not Found', message: `Trip ${tripId} not found.` });
        return;
      }

      const days = trip.days.map((d: any) => ({
        dayNumber: d.day_number,
        date: d.date,
        theme: d.theme,
        summary: d.summary,
        activities: (d.activities || []).map((a: any) => ({
          ...a,
          startTime: a.start_time || a.startTime,
          endTime: a.end_time || a.endTime,
          estimatedCost: a.estimated_cost || a.estimatedCost || 0
        }))
      }));

      const totalActivitiesCost = days.reduce(
        (sum: number, d: any) => sum + d.activities.reduce((s: number, a: any) => s + (a.estimatedCost || 0), 0),
        0
      );

      const validation = (await import('../agent/validator.js')).ItineraryValidator.validate(
        days as any,
        trip.total_budget,
        totalActivitiesCost
      );

      res.status(200).json({
        tripId,
        validation
      });
    } catch (err: any) {
      res.status(500).json({
        error: 'Validation Failed',
        message: err.message || 'Failed to validate trip.'
      });
    }
  }
}
